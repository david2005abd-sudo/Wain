const { chromium } = require('@playwright/test');
const http = require('http');
const fs = require('fs');
const path = require('path');
const assert = require('assert');
const root = path.resolve('dist');
const types={'.html':'text/html','.js':'application/javascript','.css':'text/css','.json':'application/json','.png':'image/png','.svg':'image/svg+xml','.ttf':'font/ttf','.woff2':'font/woff2'};
const server=http.createServer((req,res)=>{let file=path.join(root,decodeURIComponent(req.url.split('?')[0]));if(!file.startsWith(root)){res.writeHead(403).end();return;}if(!fs.existsSync(file)||fs.statSync(file).isDirectory())file=path.join(root,'index.html');res.setHeader('Content-Type',types[path.extname(file)]||'application/octet-stream');fs.createReadStream(file).pipe(res);});
(async()=>{
 await new Promise(r=>server.listen(4173,'127.0.0.1',r));
 const browser=await chromium.launch({headless:true,args:['--no-sandbox','--enable-unsafe-swiftshader']});
 const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')console.log('BROWSER ERROR:',m.text());});
 try{
  await page.goto('http://127.0.0.1:4173',{waitUntil:'domcontentloaded',timeout:60000});
  await page.getByText('وين وجهتك اليوم؟').waitFor({timeout:30000});
  await page.waitForTimeout(10000);
  fs.mkdirSync('screenshots',{recursive:true});
  await page.screenshot({path:'screenshots/desktop.png',fullPage:true});
  console.log('INITIAL TEXT:',(await page.locator('body').innerText()).slice(0,1400));
  console.log('CANVAS:',await page.locator('canvas').count());
  assert.equal(errors.length,0,'runtime errors: '+errors.join('; '));
  await page.getByRole('tab',{name:'المحفوظات'}).click();
  await page.getByText('أماكنك المحفوظة').waitFor();
  await page.screenshot({path:'screenshots/saved.png'});
  await page.getByRole('tab',{name:'البلاغات'}).click();
  await page.getByText('بلاغات المجتمع',{exact:true}).waitFor();
  await page.getByRole('button',{name:'إضافة بلاغ'}).click();
  await page.getByRole('button',{name:'إرسال البلاغ المحلي'}).click();
  await page.getByText('اكتب اسم الشارع حتى نعرف مكان البلاغ.').waitFor();
  await page.getByRole('textbox',{name:'اسم الشارع أو المنطقة'}).fill('شارع الاختبار');
  await page.getByRole('textbox',{name:'تفاصيل البلاغ'}).fill('بلاغ محلي للتحقق من التطبيق');
  await page.getByRole('button',{name:'إرسال البلاغ المحلي'}).click();
  await page.getByText('شارع الاختبار · الآن').waitFor();
  assert((await page.evaluate(()=>localStorage.getItem('wein-v1'))).includes('شارع الاختبار'));
  await page.getByRole('tab',{name:'الخريطة'}).click();
  await page.getByRole('textbox',{name:'ابحث عن مكان أو عنوان'}).fill('بغداد مول');
  await page.getByText('بغداد مول',{exact:true}).last().click();
  await page.waitForTimeout(11000);
  await page.screenshot({path:'screenshots/route.png'});
  console.log('ROUTE:',(await page.locator('body').innerText()).includes('المسار المقترح')?'route loaded':'service error state');
  await page.getByText('العودة للاستكشاف').click();
  await page.getByRole('button',{name:'الإعدادات',exact:true}).click();
  await page.getByText('داكن',{exact:true}).click();
  await page.getByRole('button',{name:'إغلاق',exact:true}).click();
  await page.waitForTimeout(1500);await page.screenshot({path:'screenshots/dark.png'});
  const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
  mobile.on('pageerror',e=>errors.push(e.message));
  await mobile.goto('http://127.0.0.1:4173',{waitUntil:'domcontentloaded',timeout:60000});
  await mobile.getByText('وين وجهتك اليوم؟').waitFor();await mobile.waitForTimeout(4000);
  await mobile.screenshot({path:'screenshots/mobile.png',fullPage:true});
  await mobile.getByRole('button',{name:'بلّغ',exact:true}).click();
  await mobile.getByText('شنو حالة الطريق؟').waitFor();await mobile.waitForTimeout(800);await mobile.screenshot({path:'screenshots/mobile-modal.png'});
  assert.equal(errors.length,0,'runtime errors: '+errors.join('; '));
  await mobile.getByRole('button',{name:'إغلاق',exact:true}).click();
  await mobile.getByText('بغداد، العراق',{exact:true}).click();
  await mobile.getByText('أربيل',{exact:true}).click();
  await mobile.getByText('أربيل، العراق',{exact:true}).waitFor();
  await mobile.waitForTimeout(2000);
  await mobile.screenshot({path:'screenshots/erbil.png'});
  console.log('PASS: Desktop, mobile, tabs, report validation, local persistence, route request, theme switch, and city navigation.');
 }finally{await browser.close();server.close();}
})().catch(e=>{console.error(e);server.close();process.exit(1);});
